/**
 * رقم الفاتورة موحَّداً للمقارنة — لا للعرض ولا للحفظ.
 *
 * كان كشفُ «الفاتورة مسجّلة مسبقاً» يقارن النصّ حرفاً بحرف. والمزامنة
 * تأخذ الرقم من اسم الملفّ («04»)، والنموذج يقرؤه من الورقة بلا أصفار
 * («4»). فصورةٌ ثانية للفاتورة نفسها مرّت فاتورةً ثانية، وخُصم رصيد
 * المورّد عليها: دَينٌ وهميّ بقيمتها.
 *
 * فيُوحَّد: الأرقام العربية لاتينيّة، والحروف كبيرة، والفواصل (فراغ · -
 * _ / . #) حدٌّ واحد، والحرف والرقم المتلاصقان مقطعان، والأصفار البادئة
 * في المقطع الرقميّ تسقط. فـ«04»=«4»، و«INV/2026/00124»=«INV-2026-124»،
 * و«SI0051»=«SI-51».
 */
/**
 * رقمٌ قُرئ مقلوباً من ورقةٍ عربيّة — «0059-SI» وهو «SI-0059» (لوريفا، سبتمبر ٢٠٢٦):
 * اتّجاهُ السطر من اليمين قدّم الأرقامَ على الحروف، فلم يطابق الرقمُ سطرَه في كشف
 * المورّد وقيل «ناقصة» و«ليست في كشفه» عن فاتورةٍ واحدة. ولا مورّدَ عندنا يُقدّم
 * الأرقامَ على حروف رقمه — فمقطعان: أرقامٌ ثمّ حروف، يُقلبان.
 */
export function unreverseInvoiceNumber(raw: string): string {
  const m = raw.trim().match(/^(\d+)([-/_ ])([A-Za-z]+)$/);
  return m ? `${m[3]}${m[2]}${m[1]}` : raw;
}

/** الأرقامُ العربيّة والفارسيّة لاتينيّةً — أوّلُ خطوةٍ في كلّ توحيدٍ لرقم فاتورة. */
export function latinDigits(raw: string): string {
  return raw
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x06f0));
}

/*
 * ── ثلاثُ صيغٍ لثلاثة أسئلة، وأساسُها واحد ──
 *
 * كانت ثلاثَ دوالّ في ثلاثة ملفّات لا تتّفق حتّى على الأرقام العربيّة: «٠٤»
 * مفتاحُه غيرُ «04» عند التوأم ومطابقة الكشف. فصار أساسُها واحداً هنا
 * (`latinDigits` + `unreverseInvoiceNumber`)، ويبقى الفرقُ المقصود وحده:
 *
 *   `normalizeInvoiceNumber` — **للتنبيه** («مسجّلة مسبقاً»): تُسقط الأصفار
 *     البادئة، فـ«04»=«4». إنسانٌ يرى التنبيه ويقرّر.
 *   `invoiceNumberKey` (`invoice-twin.ts`) — **للحكم الآليّ** (رفضُ نسخة، تبنّي
 *     ملفّ، استبدالُ قيد): الأصفارُ تبقى، فـ«05297» غيرُ «5297» — دمجُ فاتورتين
 *     آلياً أسوأ من تنبيهٍ فائت.
 *   `normalizeRef` (`statement-match.ts`) — **للاحتواء** في مرجع كشفٍ طويل.
 */
export function normalizeInvoiceNumber(raw: string | null | undefined): string {
  if (!raw) return "";
  return latinDigits(unreverseInvoiceNumber(raw)
    .trim())
    .toUpperCase()
    .replace(/([A-Z؀-ۿ])(\d)/g, "$1 $2")
    .replace(/(\d)([A-Z؀-ۿ])/g, "$1 $2")
    .split(/[\s\-_/.#\\]+/)
    .filter(Boolean)
    .map((part) => (/^\d+$/.test(part) ? part.replace(/^0+(?=\d)/, "") : part))
    .join("-");
}

/** رقمان لفاتورةٍ واحدة؟ — والفارغ لا يساوي شيئاً. */
export function sameInvoiceNumber(a: string | null | undefined, b: string | null | undefined): boolean {
  const x = normalizeInvoiceNumber(a);
  return x !== "" && x === normalizeInvoiceNumber(b);
}
