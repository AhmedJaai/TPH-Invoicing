/**
 * الجاهزُ يُشترى ويُباع كما هو.
 *
 * ── لماذا لا يكفي ملفُّ الوصفات ──
 *
 * كتالوج فودكس يحمل لهذه الأصناف **تغليفَها وحده**: «تشيز مدريد»
 * وصفتُه شوكةٌ وعلبةٌ بـ٠٫٧٦ ريالاً، **والكعكةُ ليست فيها**. وأربعةَ
 * عشر صنفاً بلا وصفةٍ أصلاً — ماءٌ وبراوني وكوكيز وكرنشي ويفر.
 *
 * وأثرُ ذلك أنّ مبيعَها **لا يُخصَم من المخزون**: كلُّ قطعةٍ تُشترى
 * تظهر «فرقاً» في آخر الأسبوع. وعلى أسبوعٍ حقيقيّ كان ذلك ٤٧٨ وحدةً
 * بـ٧٬٨٣٩ ريالاً — ربعَ ما يُباع.
 *
 * ── والاقترانُ مُثبَتٌ لا مخمَّن ──
 *
 * قال صاحبُ المقهى (٢١ سبتمبر ٢٠٢٦): **«الكعكات ومنتجات الحلى كلّها
 * منتجاتٌ جاهزة أشتريها»**. فالوصفةُ لكلٍّ منها قطعةٌ واحدة من صنفه.
 *
 * وأيُّ صنفٍ يقابل أيَّ منتج **يُتحقَّق منه بالكلفة المعلَنة عند
 * فودكس** قبل أن يُكتب: خمسةٌ منها تطابق إلى الهللة (براوني ٦٫٦٠،
 * وكوكيز ٤٫٥٠، وكيكة الباشن ١٢٫٠٠، وCrinkle ٥٫٠٠، وBrown Butter
 * ٦٫٠٠)، وسائرُها دون ١٣٪ — والفارقُ فيها تغليفٌ لا يعدّه فودكس في
 * كلفته. **فالجدولُ أدناه اقتراحٌ تسنده واقعة، لا تخمينَ اسم.**
 *
 * وما لم تسنده الكلفة يُعلَن ولا يُكتَم — «كرنشي ويفر» صنفُه بسبعة
 * ريالات والمعلَنة ٥٫١٠: الاقترانُ صحيحٌ في الاسم والمعنى، والكلفةُ
 * المعلَنة قديمة. فيُعرَض الفارقُ ليقرّر فيه إنسان.
 */

