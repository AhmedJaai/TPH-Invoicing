/**
 * فارقُ الكلفة المحسوبة عن المعلَنة، بنقاط الأساس — و`null` حين لا
 * كلفةَ معلَنة.
 *
 * وهو **شهادةٌ على الاقتران**: قاربتِ المحسوبةُ المعلَنةَ فالصنفُ هو
 * هو، وباعدتها فيُنظَر. ولا يُمنَع الاقترانُ بالفارق — يُعرَض معه.
 */
export function corroborationGapBp(
  computedMinor: number | null,
  declaredMinor: number | null,
): number | null {
  if (computedMinor === null || declaredMinor === null || declaredMinor <= 0) return null;
  return Math.round((Math.abs(computedMinor - declaredMinor) * 10_000) / declaredMinor);
}

/** فوق هذا يُعرَض الفارقُ تنبيهاً — وهو حدُّ «تغليفٌ لا يعدّه فودكس». */
