import { isValidSaudiVat } from "./validation";

/**
 * مورّدٌ بلا شهادة ضريبيّة — فاتورتُه بلا ضريبة أصلاً، لا «ناقصة».
 *
 * أوراق الزيتون ليس عنده سجلٌّ ضريبيّ ولا يصدر فواتير ضريبيّة (أحمد، ١ نوفمبر ٢٠٢٦)، فكانت واحدةٌ وسبعون
 * فاتورةً من فواتيره تحمل شارةً حمراء «ناقصة» و«ينقصها: الرقم الضريبيّ» وليس ينقصها شيء: لا ضريبةَ تُخصم منها
 * ولا ركنَ تطلبه من مورّدٍ لا يملكه. والحكمُ المخزَّن (`INVALID`) يبقى كما هو — هو ما يمنع خصمَها من الإقرار —
 * وهذا للعرض وحده.
 *
 * ولا يكفي ضريبةٌ صفرٌ: مورّدٌ مسجَّلٌ قُرئت ضريبتُه صفراً خطأً عطبٌ لا يُخفى. فالشرطُ كلُّه: ملفُّ المورّد بلا رقمٍ
 * ضريبيّ، والفاتورةُ ضريبتُها صفر، وما قُرئ «رقماً ضريبياً للبائع» ليس رقماً ضريبيّاً (سجلٌّ تجاريّ مثلاً).
 */
export function isUntaxedInvoice(i: { vatMinor: number | null; sellerVat: string | null; supplierVat: string | null }): boolean {
  return !i.supplierVat && (i.vatMinor ?? 0) === 0 && !isValidSaudiVat(i.sellerVat);
}

export const UNTAXED_LABEL = "بلا ضريبة";
export const UNTAXED_HINT = "المورّد غير مسجّل في الضريبة، فلا ضريبةَ تُخصم من فواتيره";
