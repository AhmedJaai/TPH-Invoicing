/**
 * الأرقامُ العربيّة‑الهنديّة (٠-٩) والفارسيّة (۰-۹) إلى اللاتينيّة — **موضعٌ واحد**.
 *
 * كان هذا السطر منسوخاً في أحد عشر ملفّاً، وبعضُها ينسى الفارسيّة: فمبلغٌ في كشفٍ
 * مصوَّر «1۲3» كانت تسقط خانتُه الوسطى فيُقرأ ١٣ بلا شكوى. والفاصلةُ العشريّة
 * وفواصلُ الآلاف ليست من شأن هذه الدالّة — كلُّ قارئٍ يقرّر فيها بحسب ما يقرأ.
 *
 * **ولا تُستعمَل في هويّة حركة البنك** (`bank/canonical.ts`): تلك لها توحيدُها
 * الثابت، وتغييرُه يغيّر بصمةَ ما استُورد.
 */
export function latinDigits(value: string): string {
  return value.replace(/[٠-٩۰-۹]/g, (d) => {
    const code = d.charCodeAt(0);
    return String(code >= 0x06f0 ? code - 0x06f0 : code - 0x0660);
  });
}
