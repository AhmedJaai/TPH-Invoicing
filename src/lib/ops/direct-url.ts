/**
 * اتّصالُ الهجرات مباشرٌ لا عبر المجمِّع.
 *
 * نقطةُ Neon المجمَّعة (`…-pooler.…`) مجمِّعٌ بنمط المعاملة: الجلسةُ التي
 * يفتحها العميل لا تملك اتّصالاً بعينه بالخادم. وقفلُ الهجرات قفلٌ استشاريٌّ
 * على **الجلسة** — فيُؤخَذ على اتّصالٍ في المجمِّع، ويُغلَق العميلُ فيبقى
 * الاتّصالُ حيّاً في المجمِّع والقفلُ عليه. وقع في ٢٦ سبتمبر ٢٠٢٦: بقي القفلُ
 * معلَّقاً على قاعدتي الإنتاج والمعاينة، فسقط نشرُ المعاينة بعد نشر الإنتاج
 * بثوانٍ «تشغيلٌ آخر لم يُفرِج عن القفل» — ولا تشغيلَ آخر.
 *
 * والتطبيقُ يبقى على المجمَّعة (غيرُها تنفد اتّصالاتُه تحت Vercel)؛ الهجراتُ
 * وحدها — اتّصالٌ واحد في البناء — تأخذ المباشر، وهو ما توصي به Neon.
 * وما ليس نقطةً مجمَّعة يُعاد كما هو.
 */
export function directDatabaseUrl(url: string): string {
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return url;
  }
  const [first, ...rest] = parsed.hostname.split(".");
  if (!first.endsWith("-pooler")) return url;
  parsed.hostname = [first.slice(0, -"-pooler".length), ...rest].join(".");
  return parsed.toString();
}
