/**
 * أيّ دليلٍ يدلّ على **جهةٍ واحدة لا غير**، وأيّه قد يشترك فيه اثنان.
 *
 * كان القيد واحداً للجميع: `(النوع، القيمة)` فريدٌ مهما كان النوع. فصار
 * اسمُ «محمد» — أو «مؤسسة التجارة» — حكراً على أوّل من سُجّل به، وامتنع
 * أن يوجد في النظام محمدان. وهذا خطأ في الواقع لا في القاعدة: الاسم
 * ليس هويّة، والسعوديّة فيها آلاف «مؤسسة الرياض للتجارة».
 *
 * والفرق ليس شكلياً: رقم الحساب والآيبان ورقم الهوية ورقم التاجر أرقامٌ
 * تُصدرها جهةٌ رسمية ولا تتكرّر — فاشتراك جهتين فيه خطأُ بياناتٍ يجب أن
 * يُعرَض. أمّا الاسم والمرجع فيتكرّران بطبيعتهما، واعتبار تكرارهما
 * «تضارباً» يُغرق صاحب العمل بتنبيهاتٍ لا خطأ فيها.
 *
 * ولذلك: التضارب يُعلَن في القاطع، ويُقبَل الاشتراك في الظنّي — على أنّ
 * الظنّي المشترك **لا يُعرِّف جهةً وحده**، لأنّه لم يعد يدلّ على واحدة.
 */
export type EvidenceKind =
  | "NAME" | "ACCOUNT" | "IBAN" | "NATIONAL_ID" | "MERCHANT_ID" | "REFERENCE"
  | "PATTERN";

/** الأدلّة القاطعة: أرقامٌ رسميّة لا تدلّ على جهتين. */
export const EXCLUSIVE_KINDS: readonly EvidenceKind[] = [
  "ACCOUNT", "IBAN", "NATIONAL_ID", "MERCHANT_ID",
];

/**
 * الأدلّة الظنّية: تتكرّر بطبيعتها فلا تُحتكَر.
 *
 * والنمط منها: «حوالات تحت الطلب … شركة …» شكلٌ قد يشترك فيه اثنان.
 * فإن اشترك سقط من الذاكرة كما يسقط الاسم المشترَك — لأنّه لم يعد
 * يدلّ على واحدة، لا لأنّه صار خطأً.
 */
export const SHARED_KINDS: readonly EvidenceKind[] = ["NAME", "REFERENCE", "PATTERN"];

export function isExclusive(kind: EvidenceKind): boolean {
  return EXCLUSIVE_KINDS.includes(kind);
}

/**
 * هل يُعدّ وجودُ هذا الدليل عند جهةٍ أخرى **تضارباً** يُعرَض؟
 *
 * في القاطع: نعم — رقمُ حسابٍ واحد لجهتين إمّا خطأٌ سابق وإمّا حسابان
 * لشخصٍ واحد، وكلاهما قرارُ إنسان.
 * في الظنّي: لا — اسمان متطابقان لجهتين أمرٌ عاديّ.
 */
export function isConflict(kind: EvidenceKind, sameCounterparty: boolean): boolean {
  if (sameCounterparty) return false;
  return isExclusive(kind);
}
