import { sql, type SQL } from "drizzle-orm";
import { db } from "@/db";
import { bankTransactions } from "@/db/schema";

/**
 * ما ينتظر قرار الإنسان — **تعريفٌ واحد**.
 *
 * كان لسؤالٍ واحد ثلاثةُ أجوبة، ولكلٍّ منها شاشة. ثمّ وُضع
 * `countPendingWork()` ليوحّدها — ونُسخ فيه **الشرط الخاطئ**:
 * ‏`lifecycle in ('RAW','INFERRED','SUGGESTED')` وحده. و`lifecycle`
 * طبقةٌ تصف رحلة الحركة، لا حالَ القرار فيها؛ فبقيت في الطابور:
 *
 *   • **خمسُ حركاتٍ مطابَقةٌ ومدفوعة** — لها دفعة وتخصيصاتها مكتوبة،
 *     ولم تتقدّم `lifecycle` من `RAW`. فتُعرَض «تنتظر تأكيدك» وهي
 *     مقضيّة، وزرُّ التأكيد يردّها الخادمُ بحقّ: «مطابَقة أصلاً».
 *   • **اثنتان وثلاثون حركة `IGNORED`** — رسومُ شبكة وضرائبُها ورواتب،
 *     أُعلن أنّها ليست سداداً. وهي **قرارٌ تامّ** لا سؤالٌ معلَّق.
 *
 * ─────────────────────────────────────────────────────────────
 *
 * ثمّ تبيّن أنّ الشرط الذي حلّ محلّه أخطأ في الجهة الأخرى، وهو أغلى:
 *
 * **للحركة سؤالان لا سؤالٌ واحد.**
 *
 *   ١. **من هذه الجهة؟** — يُجيبه التصنيف. ومن أجابه إنسانٌ
 *      (`classification_source = 'HUMAN'`) فقد أُغلق.
 *   ٢. **أيّ فاتورة تسدّدها؟** — ولا يُطرَح إلّا إذا كان جوابُ الأوّل
 *      «سدادُ مورّد». ويُجيبه قيدُ الدفعة.
 *
 * وكان الشرطُ يطوي الثاني بجواب الأوّل. وذلك صحيحٌ في كلّ بابٍ **إلّا
 * سدادَ المورّد**: من قال «هذه رسمٌ بنكيّ» قال ضمناً إنّها ليست سداد
 * فاتورة، فانتهى أمرُها. ومن قال «هذه لأوراق الزيتون» لم يقل إنّها
 * قُيِّدت — بل **بدأ** عملَها.
 *
 * وقِيس على قاعدة أحمد فوقع: **عشرون حوالةً لموردين، بـ٧٢٬٩٠٤٫٦٨
 * ريالاً**، عرّفها أحمد بيده واحدةً واحدة — فخرجت كلُّها من الطابور في
 * اللحظة نفسها، ولا دفعةَ لواحدةٍ منها. فتقول صفحةُ «مصنع الكوب
 * الذهبي» إنّ عليه ٢٥٬٥٠٩٫٨٨ وقد سدّدها أحمد على أربع حوالات، ولا
 * موضعَ في النظام يسأل عنها. **والعملُ الذي يختفي لا يُنجَز.**
 */
export function pendingDecision(): SQL {
  return sql`${bankTransactions.matchedPaymentId} is null
    and ${bankTransactions.matchStatus} <> 'IGNORED'
    and (
      /* ١ · لم يُعرَف بعدُ من الجهة */
      (
        ${bankTransactions.lifecycle} not in ('CONFIRMED','POSTED')
        and ${bankTransactions.classificationSource} is distinct from 'HUMAN'
      )
      /*
        ٢ · أو عُرفت الجهة وهي مورّد — فالمال لم يُقيَّد بعد.
        ويخرج منه بقيّةُ الأبواب: الراتبُ والرسمُ والسدادُ الحكوميّ
        ليس فيها ما يُخصَّص على فاتورة.
      */
      or (
        ${bankTransactions.direction} = 'DEBIT'
        and ${bankTransactions.category} = 'SUPPLIER'
      )
    )`;
}

export async function countPendingWork(): Promise<number> {
  const [row] = (
    await db.execute<{ n: number }>(sql`
      select count(*)::int as n
      from ${bankTransactions}
      where ${pendingDecision()}
    `)
  ).rows;

  return Number(row?.n ?? 0);
}
