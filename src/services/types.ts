/**
 * أنواع مشتركة بين الخدمات.
 *
 * الخدمات طبقة داخلية في التطبيق نفسه، لا خدمات مصغّرة. الغرض منها أن
 * تتحمّل الواجهة البرمجية مسؤوليةً واحدة — استقبال الطلب والردّ — وأن
 * ينتقل المنطق إلى وحدات تُقرأ وتُختبر على حدة.
 */
import type { db } from "@/db";

/** معاملة قاعدة بيانات كما تمرّرها drizzle إلى الدالة الداخلية. */
export type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];

/**
 * مقبضُ كتابةٍ وقراءة: القاعدةُ أو معاملةٌ جارية.
 *
 * وبه تُختبَر الخدمةُ **على المخطّط الحقيقيّ** في معاملةٍ تُلغى — كما
 * في `payment.service` و`recordAudit`. والخدمةُ التي لا تقبله لا
 * تُختبَر إلّا بكتابةٍ تبقى، وذلك يمنع اختبارها أصلاً فيبقى مسارُها
 * دعوى.
 *
 * و`.transaction` موجودةٌ في الطرفين: على القاعدة تفتح معاملة، وعلى
 * المعاملة تفتح نقطةَ حفظٍ داخلها — فيصحّ النداءُ في الحالين.
 */
export type Conn = typeof db | Tx;

/** سطر فاتورة كما يصل من الاستخراج، بنصوصه لا بأرقامه. */
export interface RawLine {
  description: string;
  quantity: string;
  unitPrice: string;
  lineTotal: string;
}
