-- 072 — فاتورةٌ محجوزة يُدخلها صاحبُها الدفعةَ بقراره وسببه.
--
-- قرارُ المالك بإدخال فاتورةٍ محجوزة في دفعة الشهر (قاعدةُ ٧ أكتوبر ٢٠٢٦: يُنبَّه ولا
-- يُمنَع). كان قسمُ «محجوزٌ حتى تُعالَج» يعرض السببَ وزرَّ واتساب وحدهما، فمن أراد أن
-- يدفع لمورّدٍ لا يسلّم قبل السداد لم يجد طريقاً إلّا خارج النظام.
--
-- صفٌّ لكلّ فاتورةٍ أُدخلت: سببُ حجزها لحظةَ القرار، وما كتبه صاحبُ القرار، ومن ومتى.
-- وحذفُ الصفّ «أعِدها إلى الحجز» — قرارٌ لا مال، وأثرُه في audit_logs في الحالين.
-- والدفعةُ تُبنى في الخادم: الصفُّ يُدخل الفاتورةَ بمبلغها ولا يحمل مبلغاً.
--
-- جدولٌ جديد: إضافةٌ خالصة، والشيفرةُ القديمة لا تعرفه.

create table if not exists payment_hold_overrides (
  invoice_id    text primary key references invoices(id) on delete cascade,
  hold_reason   text not null,
  note          text not null,
  created_by_id text references users(id),
  created_at    timestamptz not null default now()
);
