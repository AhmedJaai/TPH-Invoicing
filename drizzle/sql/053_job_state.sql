-- 053 — بصمةُ آخر تشغيلٍ لعملٍ خلفيّ.
--
-- الاستدراكُ (اعتمادُ ما اجتمعت شروطُه، والقيدُ من القراءة المحفوظة، وخصمُ الأرصدة،
-- وربطُ الحوالات) يجري عند فتح أيّ صفحةٍ مرّةً كلَّ عشر دقائق لكلّ جهاز — ولو لم
-- يتغيّر شيء: يقرأ القراءاتِ والحركاتِ كلَّها ويفتح معاملةً لكلّ مورّد. فتُحفظ هنا
-- بصمةُ ما يعمل عليه؛ فإن لم تتغيّر ولم يمضِ حدٌّ من الوقت لم يُعَد.
--
-- جدولٌ جديد: إضافةٌ آمنة.
create table if not exists job_state (
  name        text primary key,
  fingerprint text not null,
  ran_at      timestamptz not null default now()
);
