--  حدّ الطلبات
-- ═══════════════════════════════════════════════════════════════════
--
--  واجهة التحليل تستهلك حصّة نموذج، وواجهة استيراد البنك تقرأ ملفاً بحجم
--  خمسة عشر ميجابايت في الطلب الواحد. وحلقةٌ واحدة تستنفد حصّة اليوم كلّها
--  فيقف عمل صاحب المقهى.
--
--  والعدّاد في ذاكرة العملية لا يصلح: البيئة السحابية تُشغّل نسخاً متعدّدة،
--  فكل نسخة تعدّ وحدها ويصير الحدّ الفعلي أضعافه. فالعدّ في القاعدة.

CREATE TABLE IF NOT EXISTS rate_limits (
  key          text        NOT NULL,
  window_start timestamptz NOT NULL,
  count        integer     NOT NULL DEFAULT 0,
  PRIMARY KEY (key, window_start)
);

-- النوافذ المنقضية تُنظَّف عند أول طلب بعدها؛ والفهرس يجعل ذلك رخيصاً
CREATE INDEX IF NOT EXISTS rate_limits_window_idx ON rate_limits (window_start);
