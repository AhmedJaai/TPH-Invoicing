-- 110 — من أين دُفع المصروف (٢٣ نوفمبر ٢٠٢٦): «في اشياء تدفع نقدا من الصندوق» (أحمد).
--
-- المصروفُ اليدويّ كان بلا مصدر: نقدُ الصندوق وحسابُ المالك والدفعُ بغير الكشف سواء، فلا يُعرف كم
-- صُرف من نقد المبيعات ولا يُقابَل بما سجّله فودكس نقداً. فصار له `paid_from`: `TILL` نقدُ الصندوق،
-- `OWNER` حسابُ المالك، `OTHER` غيرُ ذلك؛ والفارغُ «لم يُقَل» (المصروفُ المشتقّ من البنك، وما قبل هذا).
-- إضافةٌ خالصة.

alter table expenses add column if not exists paid_from text
  check (paid_from is null or paid_from in ('TILL', 'OWNER', 'OTHER'));
