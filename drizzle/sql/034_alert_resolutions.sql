-- تنبيهاتٌ تُغلَق — قرارُ الإنسان في «سُدّد مرّتين»
--
-- كان أوّل بندٍ في «ما يحتاج انتباهك» سداداً مزدوجاً بتاريخ ١٥ يوليو،
-- حرجاً أحمر، ولا فعلَ له: طالَب أحمد الجهة أو استردّ المال أو تبيّن
-- أنّه ليس ازدواجاً — والبند باقٍ كما هو. والحرجُ الدائم يعلّم تجاهلَ
-- الحرج، فيضيع الحرجُ الحقيقيّ حين يقع.
--
-- فالقرار يُحفَظ بمفتاح التنبيه لا بمعرّفٍ يُولَّد: `double:<txA>:<txB>`
-- بمعرّفات الحركات مرتَّبةً — فيُعاد اشتقاقه من الحركات نفسها في كلّ
-- حساب، وإن تغيّرت المجموعة (دخلت حركةٌ ثالثة) تغيّر المفتاح فعاد السؤال.
--
-- والقرار ثلاثة: «طالبتُ» يُبقي البند بحالٍ أهدأ (المال لم يعد بعد)،
-- و«استُردّ» و«ليس ازدواجاً» يُغلقانه. وكلّ قرارٍ في سجلّ التدقيق.
-- ═══════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS alert_resolutions (
  key      text PRIMARY KEY,
  decision text NOT NULL,
  note     text,
  user_id  text REFERENCES users(id),
  at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT alert_resolutions_decision_chk
    CHECK (decision IN ('CLAIMED', 'RECOVERED', 'NOT_DUPLICATE')),
  CONSTRAINT alert_resolutions_key_chk
    CHECK (key ~ '^[a-z]+:[A-Za-z0-9_-]+(:[A-Za-z0-9_-]+)+$')
);
