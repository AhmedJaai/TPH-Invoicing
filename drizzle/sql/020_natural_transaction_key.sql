-- هوية الحركة تصير مفتاحاً طبيعيّاً لا بصمةً تُحسَب
--
-- وقع في قاعدة أحمد ما يُفترَض أنّه ممنوع: استُورد الكشف نفسه مرّتين
-- فدخلت ألفٌ وأربعمئة وثلاث عشرة حركة مضاعفةً — تسعمئة واثنا عشر ألف
-- ريال. والمنع كان قائماً ولم يمنع.
--
-- والسبب أنّ المنع كان معلَّقاً على **بصمة تُحسَب بدالّة**
-- (`transactionIdentity`)، والدالّة تغيّرت: خرج منها رقم الحساب. فحركةٌ
-- واحدة بعينها — نفس التاريخ ونفس المبلغ ونفس الوصف حرفاً بحرف — صار
-- لها بصمتان: واحدة كُتبت قبل التغيير وأخرى بعده. فلم يرَ الاستيراد
-- الثاني الأوّل.
--
-- **والدرس: تغييرُ دالّة الهوية يُبطل بأثرٍ رجعيّ كلَّ ما حُفظ بها.**
-- وكلّ بصمةٍ محسوبة تحمل هذا الخطر ما دامت الشيفرة تتغيّر.
--
-- فصار القيد على المفتاح **الطبيعيّ** نفسه — الحساب والتاريخ والمبلغ
-- والاتجاه والوصف الموحَّد وترتيب التكرار. وهذه ليست تمثيلاً للحركة،
-- هي الحركة. ولا «نسخة» لها تتغيّر بتغيّر الشيفرة.
--
-- ═══ وترتيب التكرار جزء من المفتاح عمداً ═══
--
-- لأنّ الكشف الواحد قد يذكر حركتين متطابقتين في اليوم — رسمَين، أو
-- حوالتين لمورّدٍ واحد بفاتورتين — وهما حقيقيّتان. وفي كشف أحمد ثلاث
-- وعشرون مجموعةً كهذه.
--
-- فالملف الذي يذكرها مرّتين يعطيها الترتيبين ٠ و١. وإن رُفع عشرين
-- مرّة أعطاها ٠ و١ في كلّ مرّة — والقيد يردّ ما بعد الأولى. وإن جاء
-- كشفٌ أطول يذكرها ثلاثاً دخلت الثالثة وحدها بالترتيب ٢.
--
-- وبهذا: رفعُ الملف عشرين مرّة لا يزيد حركةً واحدة، والحركة الحقيقية
-- المتكرّرة لا تُبتلَع.
-- ═══════════════════════════════════════════════════════════════

alter table bank_transactions
  add column if not exists occurrence integer not null default 0;

-- ترقيمٌ للقائم: نفس ترتيب `db:dedupe` — المرتبط بدفعة أوّلاً فلا
-- يُزحزَح ما يُثبت سداداً، ثمّ الأقدم استيراداً.
with ranked as (
  select t.id,
         row_number() over (
           partition by coalesce(t.bank_account_id, '~'), t.value_date, t.amount_minor,
                        t.direction,
                        upper(btrim(regexp_replace(coalesce(t.description,''), '\s+', ' ', 'g')))
           order by (t.matched_payment_id is null), i.created_at, t.id
         ) - 1 as occ
  from bank_transactions t
  join bank_imports i on i.id = t.bank_import_id
)
update bank_transactions t
set occurrence = r.occ
from ranked r
where t.id = r.id and t.occurrence <> r.occ;

create unique index if not exists bank_tx_natural_uniq
  on bank_transactions (
    coalesce(bank_account_id, '~'),
    value_date,
    amount_minor,
    direction,
    upper(btrim(regexp_replace(coalesce(description,''), '\s+', ' ', 'g'))),
    occurrence
  );

comment on column bank_transactions.occurrence is
  'ترتيب هذه الحركة بين مثيلاتها في الكشف — جزءٌ من المفتاح الطبيعيّ، وبه تنجو الحركتان المتطابقتان الحقيقيّتان';
