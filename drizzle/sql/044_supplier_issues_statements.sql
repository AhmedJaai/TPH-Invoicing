-- 044 — سياسةُ الكشف: أيصدر المورّدُ كشفَ حساب؟
--
-- «كشوف الحساب مو كلّهم يصدرونها» (أحمد، ٢٤ سبتمبر ٢٠٢٦). كان بندُ «لم
-- يصل كشفُه» يطلب كشفاً من كلّ مورّدٍ له فاتورةٌ في الشهر — ومن لا يصدره
-- يبقى في القائمة شهراً بعد شهر، فيتعلّم صاحبُ المقهى تجاهلَها كلَّها.
-- فيُعلَن كما تُعلَن سياسةُ الفواتير (035): يكتبه الإنسان ولا يُشتقّ.
--
-- إضافةٌ بقيمةٍ افتراضيّة — آمنةٌ للشيفرة القديمة التي لا تقرؤه.
alter table suppliers add column if not exists issues_statements boolean not null default true;
