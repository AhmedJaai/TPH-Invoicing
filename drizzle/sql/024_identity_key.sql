-- ═══════════════════════════════════════════════════════════════
-- هويّة الحركة تُخزَّن، ولا تُحسَب في كل مرّة
--
-- كان التعرّف على «هل هذه الحركة عندنا؟» يقوم على مقارنةٍ تُحسَب وقت
-- الاستيراد: التاريخ والمبلغ والاتجاه والوصف. وهي مقارنةٌ هشّة أمام
-- الواقع — البنك يعيد تصدير الفترة نفسها بوصفٍ مختلف قليلاً، فتصير
-- الحركة الواحدة حركتين.
--
-- والصواب أنّ للحركة **هويّةً مخزَّنة** تُقيَّد في القاعدة:
--
--   `REF:<حساب>|<مرجع العمليّة>`   حين يعطي البنك رقماً للعمليّة
--   `FACT:<حساب>|<تاريخ>|<مبلغ>|<اتجاه>|<وصف موحَّد>|<ترتيب>`  وإلّا
--
-- والأولى هي القويّة: وصفُ الحوالة يتغيّر ورقمُها لا يتغيّر. والثانية
-- احتياطٌ لما لا رقم له — رسومٌ وأمثالها — وفيها الترتيب آخرَ شيء، كي
-- تنجو الحركتان المتطابقتان الحقيقيّتان في اليوم الواحد.
--
-- ولا يمنع القيدُ حركةً مشروعة: العمليّتان المختلفتان لهما مرجعان
-- مختلفان، والمتطابقتان بلا مرجع يفرّقهما الترتيب.
-- ═══════════════════════════════════════════════════════════════

alter table bank_transactions
  add column if not exists identity_key text;

create unique index if not exists bank_tx_identity_uniq
  on bank_transactions (identity_key)
  where identity_key is not null;

create index if not exists bank_tx_period_idx
  on bank_transactions (coalesce(bank_account_id, '~'), value_date);

comment on column bank_transactions.identity_key is
  'هويّة الحركة المخزَّنة: REF بمرجع العمليّة، أو FACT بالوقائع والترتيب. وبها يُعرَف ما هو عندنا قبل أن يُحسَب أيّ شيء آخر';
