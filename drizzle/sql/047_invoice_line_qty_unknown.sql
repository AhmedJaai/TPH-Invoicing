-- 047 — كمّيّةُ البند قد تكون «غير معروفة».
--
-- كان العمودُ `not null default 1`، والشيفرةُ تكتب ١ لكلّ كمّيّةٍ لم تُقرأ
-- (والأرقامُ العربيّة تُمحى فتصير ١، و«0» تصير ١). فيحسب الجردُ كيساً واحداً
-- حيث لا يُعرف شيء — والمجهولُ ليس واحداً ولا صفراً.
--
-- إسقاطُ القيد وحده: إضافةٌ آمنة — الشيفرةُ القديمة تكتب قيمةً دائماً،
-- والقراءُ (الجرد، ملفُّ الصنف) يعرفون الفراغ «الكمّيّة غير مقروءة».
alter table invoice_lines alter column qty drop not null;
alter table invoice_lines alter column qty drop default;
