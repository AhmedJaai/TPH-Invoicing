-- مرجع العمليّة: ما يمنع أن تُحسَب الحوالة الواحدة مرّتين
--
-- المفتاح الطبيعيّ في `020` منع أن يدخل الكشفُ مرّتين. ولم يمنع أن
-- **يذكر الكشفُ الواحد الحوالةَ مرّتين** — لأنّ `occurrence` يحمي
-- المتطابقتين بوصفهما حقيقيّتين، وهو صحيحٌ في الرسوم: كشفُ أحمد فيه
-- ستّ عشرة مجموعة «CITY:Digital Channel» متكرّرة في اليوم، وهي رسومٌ
-- وقعت فعلاً.
--
-- لكنّ الحوالة تحمل ما لا يحمله الرسم: **رقم عمليّة لا يتكرّر**. وخمس
-- حوالات في تصدير الأهليّ مذكورةٌ مرّتين بمرجعٍ واحد — أربعة عشر ألفاً
-- وثلاثمئة وتسعة وسبعون ريالاً حُسبت مرّتين. رآها أحمد بعينه في حوالة
-- «مقام الثقة»: «عمليّة واحدة في نفس اليوم ونفس المبلغ حاسبها مرّتين».
--
-- والقياس قبل القيد: في ١٤٤٥ حركة، ١٢٤ لها مرجع عمليّة، والمكرَّر منها
-- خمسة — كلّها بنفس المبلغ، **ولا مرجعَ واحدٌ يخدم مبلغين**. فالقيد
-- الفريد لا يردّ حركةً حقيقيّة.
--
-- والقيمة تُحسَب في `operationRef` وحدها — دالّةٌ واحدة يكتب بها
-- المستورِد ويقرأ بها الفاحص. والقيد هنا يضمنها مهما كان الكاتب.
-- ═══════════════════════════════════════════════════════════════

alter table bank_transactions
  add column if not exists operation_ref text;

create unique index if not exists bank_tx_operation_ref_uniq
  on bank_transactions (coalesce(bank_account_id, '~'), operation_ref)
  where operation_ref is not null;

comment on column bank_transactions.operation_ref is
  'رقم العمليّة عند البنك — من تطابق مرجعُه تطابقت عمليّته. فارغٌ لحركات الشبكة وللرسوم التي لا مرجع لها';
