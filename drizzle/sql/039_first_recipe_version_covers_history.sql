--  أوّلُ نسخةٍ لكلّ وصفةٍ سارية منذ البداية
--
--  ── ما وقع ──
--
--  رُفع كتالوج فودكس في ٢١ سبتمبر ٢٠٢٦، وتاريخُ السريان الافتراضيّ
--  في الشاشة كان **أوّل الأسبوع القادم** (٢٠ سبتمبر) — بحجّةِ أنّ
--  نسخةً تبدأ اليوم تُغلق سابقتَها أمس فيُحسَب نصفُ الأسبوع بوصفةٍ
--  ونصفُه بأخرى.
--
--  وتلك الحجّةُ صحيحةٌ **حين تكون ثمّة سابقة**. وفي أوّل نسخةٍ لا
--  سابقةَ تُغلَق، فلم تفعل الحجّةُ شيئاً إلّا أن أخرجت كلَّ بيعٍ قبل
--  ذلك اليوم من الحساب:
--
--      لم يدخل الحسابَ سطرُ بيعٍ واحد — ١٧٠٦ من ١٧١٧
--      تمثّل ٩٩٫٨٪ من الوحدات المباعة بقيمة ٣٧٬٩٨٩ ريالاً
--
--  والوصفاتُ كلُّها مكتوبةٌ صحيحة، والمحرّكُ سليم، **والتاريخُ وحده
--  أبطلها**.
--
--  ── ولماذا هجرةٌ لا إصلاحٌ في الشيفرة وحدها ──
--
--  الشيفرةُ صُحِّحت: أوّلُ نسخةٍ تُكتب من `RECIPE_EPOCH`. لكنّ ما
--  كُتب قد كُتب، **وإعادةُ رفع الملفّ لا تُصلحه**: المستوردُ يقارن
--  المكوّنات فيجدها كما هي ويقول «لم تتغيّر» — وهو محقّ، فالمكوّناتُ
--  لم تتغيّر، التاريخُ هو الخطأ.
--
--  ── والتوسيعُ إلى الوراء لا يتعارض مع شيء ──
--
--  النسخةُ الأولى هي الأقدم في وصفتها بحكم كونها الأولى، فلا نسخةَ
--  قبلها تتداخل معها. ولا يُمَسّ إلّا `version = 1`: ما أُرِّخ عن
--  قصدٍ بعدها يبقى كما أُرِّخ.
-- ═══════════════════════════════════════════════════════════════

update recipe_versions
   set effective_from = '2000-01-01'
 where version = 1
   and effective_from > '2000-01-01';

comment on column recipe_versions.effective_from is
  'يومُ بدء السريان (YYYY-MM-DD) شاملاً. وأوّلُ نسخةٍ تبدأ من ٢٠٠٠-٠١-٠١ — «منذ البداية»: تصف كيف كان يُصنَع دائماً، لا كيف سيُصنَع من الغد.';
