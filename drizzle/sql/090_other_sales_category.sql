-- 090 — بابُ «مبيعات خارج فودكس» لحوالاتٍ واردة من زبونٍ يُباع له خارج الجهاز. هجرةٌ وحدها: قيمةُ التعداد لا تُستعمل في المعاملة التي أُضيفت فيها.
-- «سبعة جرة» عميلٌ يشتري منّا، وحوالاتُه إيراد). إضافةُ قيمةٍ لنوعٍ قائم في هجرةٍ وحدها:
-- `ALTER TYPE … ADD VALUE` لا تُستعمل قيمتُه في المعاملة نفسها. لا يمسّ صفّاً قائماً.
ALTER TYPE tx_category ADD VALUE IF NOT EXISTS 'OTHER_SALES';
