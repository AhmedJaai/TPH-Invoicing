-- 071 — دورُ «مدقّق»: قراءةٌ بلا كتابة.
--
-- دورُ «المراجع» (AUDITOR): قراءةٌ فقط، للمحاسب الخارجيّ. إضافةُ قيمةٍ إلى نوع `role`
-- — لا صفَّ قائماً يتغيّر، والأدوارُ الثلاثة كما هي.
--
-- ⚠ `ALTER TYPE … ADD VALUE` لا تُستعمل قيمتُه في المعاملة نفسها التي أضافته —
--   فلا يُكتب في هذه الهجرة صفٌّ بالدور الجديد. وهو آمنٌ قبل الشيفرة وبعدها:
--   الشيفرةُ لا تكتب AUDITOR إلّا حين يختاره المالك من «المستخدمون» في الإعدادات،
--   وإن لم تُطبَّق الهجرة قالت الشاشةُ ذلك ولم يتغيّر دور.

alter type role add value if not exists 'AUDITOR';
