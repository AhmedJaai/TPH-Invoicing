-- ═══════════════════════════════════════════════════════════════
-- `payment_month` تتبع المنطقة الزمنيّة — فلا تُوسَم IMMUTABLE
--
-- وُسمت في ٠٢٨ `IMMUTABLE` وهي تلفّ `to_char(timestamptz)`، وهذا يتبع
-- `timezone` الجلسة: اللحظة `2026-08-31 21:30Z` شهرُها `2026-08` في جلسة
-- UTC و`2026-09` في جلسة الرياض. والوسمُ كذبٌ على المخطِّط: يُجيز له أن
-- يحفظ الناتج ويطويه ثابتاً، وأن تُبنى عليه فهارس تفسد بتغيّر الجلسة.
--
-- فتُوسَم `STABLE` — ثابتةً داخل الاستعلام الواحد لا عبر الجلسات — وهو
-- وصفُها الحقّ. ولا يتغيّر ناتجُها اليوم: جلسةُ القاعدة UTC، والتاريخ
-- المدنيّ يُكتب `00:00Z`، والخدمات تحسب الشهر بالتوقيت نفسه. ولا فهرسَ
-- عليها (فُحص `pg_index`)، والمؤثِّرات تستدعيها كما هي.
-- ═══════════════════════════════════════════════════════════════

CREATE OR REPLACE FUNCTION payment_month(applies text, paid timestamptz) RETURNS text AS $$
  SELECT coalesce(applies, to_char(paid, 'YYYY-MM'));
$$ LANGUAGE sql STABLE;
