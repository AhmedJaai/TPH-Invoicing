-- المبلغ نفسه دليلٌ على الباب
--
-- في كشف الأهليّ رسومٌ صغيرة كثيرة لا يقول وصفها شيئاً — بل يخرج
-- بعضها بوصفٍ فارغ تماماً. وهي رسوم بنكٍ بحكم مقدارها: ريالٌ وخمسة
-- هللات، وخمسون هللة، وثلاثة ريالات. ولا مورّد يُدفَع له ثلاثة ريالات.
--
-- فصار المقدار طبقةً تُسأل بعد الكلمات وقبل إعلان الجهل: الصادر الأقلّ
-- من عشرين ريالاً — إن لم يكن ضريبةً — رسمُ بنك.
--
-- ولها مصدرها في السجلّ: `AMOUNT`. ولم تُدسّ تحت `KEYWORD` لأنّها
-- ليست كلمة، ولا تحت `RULE` لأنّها ليست قاعدةً محفوظة يُشار إليها
-- بمعرّف. ومن يقرأ «كيف عُرفت هذه؟» بعد شهر يجب أن يقرأ الحقّ.
-- ═══════════════════════════════════════════════════════════════

