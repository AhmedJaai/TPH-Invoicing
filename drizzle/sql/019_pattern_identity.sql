-- النمط دليلٌ على الجهة
--
-- ذاكرة المستفيدين كانت تُمسك الحركة من اسمه أو رقم حسابه. وفي كشف
-- أحمد الحقيقيّ **كلّ** الحركات المجهولة — خمسٌ وثمانون — بلا اسم
-- مستفيد وبلا رقم حساب: سدادٌ حكوميّ عبر «سداد»، ورسومُ نقاط بيع،
-- وأوصافٌ فارغة. فمفتاح الذاكرة يخرج فارغاً لكلّها.
--
-- وأثر ذلك أنّ «يؤكّد مرّةً فيعمّ على أمثاله» لم يكن يعمل على شيءٍ
-- ممّا يحتاجه فعلاً: يؤكّد الحركة فتُصنَّف هي وحدها، وتبقى أخواتها
-- الأربع عشرة كما كانت — ثمّ يُسأل عنهنّ واحدةً واحدة.
--
-- والذي يميّزها موجود: شكلُ الوصف بعد إسقاط أرقامه. وهو ظنّيٌّ كالاسم
-- لا قاطعٌ كالحساب — فلا يُحتكَر، وإن اشترك فيه اثنان سقط من الذاكرة.
