-- ولا يُعرَف كم دُفع لهذا وكم لتلك. ثمّ حين استُعيد «نوع العملية»
-- بالدمج انكشف الخلط وخرجت الحركات «غير مصنَّفة»: صارت تُعرَف أنّها
-- ضريبة ولا بابَ لها تُوضَع فيه.
--
-- والنظام يفصل أصلاً بين رسم الشبكة وضريبته (`POS_FEE` و`POS_VAT`).
-- وهذا هو الفصل نفسه في رسوم البنك.
