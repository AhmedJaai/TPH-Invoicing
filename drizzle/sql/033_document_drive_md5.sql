-- بصمةُ الدرايف للمستند — كي لا يُقرأ الملفّ نفسه بالذكاء مرّتين
--
-- المزامنةُ بالاسم تُقيِّد الملفّ بلا تنزيله، فلا `sha256` له. ثمّ يرفع
-- أحدٌ الملفَّ نفسه من الجهاز فلا تجده البصمة، فيُقرأ بنداءٍ مدفوع ويُعرَض
-- كأنّه جديد (غاناش CIV-008433430 وCIV-008437026).
--
-- والدرايف يعطي `md5Checksum` في القائمة نفسها بلا تنزيل. فيُحفَظ هنا،
-- ويقابله `/api/analyze` بـmd5 الملفّ المرفوع قبل القراءة. وليس فريداً:
-- قد يُرفع الملفّ نفسه في مجلّدين، والمنعُ للتكرار يقع في `sha256`.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE documents ADD COLUMN IF NOT EXISTS drive_md5 text;

CREATE INDEX IF NOT EXISTS documents_drive_md5_idx
  ON documents (drive_md5) WHERE drive_md5 IS NOT NULL;
