-- 109 — نوعُ الإجازة (٢٢ نوفمبر ٢٠٢٦): سنويّةٌ ومرضيّةٌ وبلا أجر.
--
-- كانت كلُّ «إجازة» يوماً لا يُخصم عنه ويُطرح من الرصيد السنويّ: فالإجازةُ بلا أجرٍ تُدفع كاملة،
-- والمرضيّةُ تأكل من السنويّة. فصار لليوم نوعُه: `ANNUAL` (والفارغُ سنويّةٌ كما كان) لا يُخصم ويُطرح
-- من الرصيد، و`SICK` لا يُخصم ولا يُطرح، و`UNPAID` يُخصم أجرُ يومه بلا جزاء. إضافةٌ خالصة.

alter table payroll_attendance add column if not exists leave_type text
  check (leave_type is null or leave_type in ('ANNUAL', 'SICK', 'UNPAID'));
