--  نطاقُ الجرد: أيُّ الأصناف يُحسَب فيه وأيُّها خارجَه
--
--  ── لماذا يُختار ──
--
--  في الكتالوج ستّون صنفاً، ولا يُعَدّ الستّون كلَّ أسبوع: المصّاصاتُ
--  والأكوابُ تُعَدّ بالكرتون مرّةً في الشهر، وأصنافٌ لم تصل فاتورتُها
--  بعد، وأصنافٌ لم يعد المقهى يشتريها. ومن أُلزم بعدّ ستّين صنفاً
--  كلَّ أحد **يعدّ بعضَها بالتخمين** — وتخمينٌ في خانة الفعليّ أسوأ
--  من فراغٍ فيها: الفراغُ يقول «لم يُعَدّ»، والتخمينُ يقول «هذا ما
--  على الرفّ» فيُحسَب عليه فرقٌ ويُبنى عليه قرار.
--
--  ── والاستبعادُ يُعلَن ولا يُخفي ──
--
--  الصنفُ خارج الجرد **تُحسَب وقائعُه كما هي** — افتتاحيُّه
--  ومشترياتُه واستهلاكُه المتوقَّع — ولا يُحسَب له فرق، ولا يدخل
--  مجاميعَ التقرير. ويُقال عددُه في رأس الشاشة: «تعدّ ٢٤ من ٦٠».
--  فالذي يُخفى في رقمٍ هو الذي يُخدَع به.
--
--  ── ولا يُعَدّ صفراً ──
--
--  القيدُ الرابع في المشروع: المجهولُ ليس صفراً. وصنفٌ خارج الجرد
--  ليس «صفراً على الرفّ»، هو «لم نعدّه» — فيبقى `actual_milli`
--  كما هو (فراغاً، أو رقماً أدخله إنسانٌ قبل أن يُستبعَد فلا يُدهَس).
--
--  ── والقيمةُ الافتراضيّة `true` مقصودة ──
--
--  الهجرةُ تسبق الكودَ بنشرة، فالأسطرُ القائمة تُقرأ بالكود القديم
--  الذي لا يعرف هذا العمود. و`true` تعني «كما كان» — الجردُ يشمل
--  كلَّ صنفٍ فعّال، وهو سلوكُ النظام قبل هذه الهجرة بعينه.
-- ═══════════════════════════════════════════════════════════════

alter table inventory_count_lines
  add column if not exists in_scope boolean not null default true;

comment on column inventory_count_lines.in_scope is
  'أيدخل هذا الصنفُ حسابَ هذا الجرد؟ الخارجُ تُحسَب وقائعُه ولا يُحسَب فرقُه ولا يدخل المجاميع، ويُعلَن عددُه. ولا يعني «صفرٌ على الرفّ» بل «لم نعدّه».';

-- وفهرسٌ للعدّ السريع: «كم صنفاً في هذا الجرد؟» يُسأل في كلّ فتحة شاشة
create index if not exists inventory_count_lines_scope_idx
  on inventory_count_lines (count_id, in_scope);
