-- ══════════════════════════════════════════════════════════════════
--  سياسةُ مستندات المورّد — ما يُطلَب منه وما لا يُطلَب
-- ══════════════════════════════════════════════════════════════════
--
--  كان النظام يعرف عن المورّد شيئين: `issues_invoices` و
--  `contract_on_file`. ومنهما يُشتقّ حكمٌ واحد صارم:
--
--      مورّدٌ لا يصدر فواتير وبلا عقد  ⇒  تنبيهٌ دائم
--
--  وذلك يصحّ في المورّد الذي يبيع بانتظامٍ بلا مستند. ولا يصحّ في
--  حالتين واقعتين في مقهى أحمد:
--
--   ١ · **مورّدٌ لا يحتاج عقداً أصلاً.** شراءٌ عارضٌ مرّةً في السنة، أو
--       جهةٌ صغيرة لا يُتصوَّر معها عقدُ توريد. والتنبيهُ الذي يُعرَض
--       على ما لا يُفعَل فيه شيء يُعلّم صاحبَه تجاهلَ التنبيهات كلّها —
--       وهو أغلى ما يُفقَد.
--
--   ٢ · **مورّدٌ فواتيرُه ورقيّة.** يعطي ورقةً باليد عند التسليم، فهي
--       فاتورةٌ موجودةٌ حقّاً وإن لم تُرفَع إلى النظام. وقولُ النظام
--       «لا يصدر فواتير» عنه **خبرٌ كاذب**، ويجرّ إلى مطالبته بعقدٍ لا
--       يحتاجه بدل مطالبته برفع ورقته.
--
--  فصار للمورّد حقلان يكتبهما الإنسان صراحةً:
--
--    `contract_required`  أيُطلَب منه عقدُ توريد؟ (افتراضُه: نعم)
--    `paper_invoices`     أفواتيرُه ورقيّةٌ تُسلَّم باليد؟
--
--  ولا يُشتقّان من البيانات: «لم يصل منه مستند» لا يعني «ليس له
--  مستند» — وهذا هو القيدُ الرابع في هذا المشروع: المجهولُ ليس صفراً.
--  فالافتراضُ يبقى على حاله حتى يقول الإنسانُ غيرَه.

alter table suppliers
  add column if not exists contract_required boolean not null default true;

alter table suppliers
  add column if not exists paper_invoices boolean not null default false;

comment on column suppliers.contract_required is
  'أيُطلَب من هذا المورّد عقدُ توريد؟ يكتبه الإنسان — ولا يُشتقّ من غياب المستندات.';

comment on column suppliers.paper_invoices is
  'فواتيرُه ورقيّةٌ تُسلَّم باليد. موجودةٌ حقّاً وإن لم تُرفَع — فلا يُقال عنه «لا يصدر فواتير».';

-- ── قيدٌ يمنع التناقض ──
--
--  «فواتيرُه ورقيّة» و«لا يصدر فواتير» لا يجتمعان: الأولى تقول إنّ
--  الفاتورة موجودةٌ ولم تُرفَع، والثانية تقول إنّها غير موجودة. ولو
--  اجتمعا لما عُرف أيُّهما يُعرَض ولا أيُّ طلبٍ يُرسَل إلى المورّد.
alter table suppliers
  drop constraint if exists suppliers_paper_invoices_consistent;

alter table suppliers
  add constraint suppliers_paper_invoices_consistent
  check (not (paper_invoices and not issues_invoices));
